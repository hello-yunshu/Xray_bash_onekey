#!/usr/bin/env python3
"""F18 — share links, Clash proxies and terminal QR codes.

Preview evidence level: CONTAINER_VERIFIED (config-level: the real Go binary is
executed against real Xray JSON configs generated by `xray generate`; the fixed
Bash baseline is extracted from install.sh; no Xray data plane, no systemd, no
root on the host, no network).

What the fixture proves about the Go manager:

* `xray share --json` renders a VLESS URI from the runtime config for every
  transport: Reality raw, the Reality `--transport ws` companion inbound
  (`--inbound 1`), TLS ws/gRPC/xHTTP behind a proxy and plain ws;
* Reality links carry flow/sni/fp/pbk/sid and no `target`; the Clash proxy
  mirrors the same public key and sID under `reality-opts`;
* `--public-port` overrides only the client-facing port and never rewrites the
  runtime config;
* a loopback `security=none` inbound is refused as ambiguous unless the caller
  supplies `--public-security tls|none`, which is exactly the Bash Nginx shape;
* xHTTP has no Clash rendering: the CLI warns `clash-xhttp-unsupported` instead
  of fabricating a proxy block;
* `--qr` renders the share URI through the real `qrencode -o - -t utf8`, byte
  for byte the same matrix Bash prints; the flag is opt-in, so the default text
  and `--json` contracts are unchanged and `--json --qr` is rejected.

Everything the Bash baseline does differently is recorded in
`baseline-compare.json` instead of being claimed as parity (`target=`
parameter, `fp=chrome` on TLS/none links, xHTTP Clash block, Clash
fingerprint/skip-cert-verify keys, Chinese fragment names, the URL-quoted
path template and Bash printing QR codes for every link automatically).
"""
import hashlib
import json
import os
import re
import shutil
import stat
import subprocess
import sys
from pathlib import Path
from urllib.parse import parse_qs, urlsplit

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fixture_support import run_fixture  # noqa: E402

PBK = re.compile(r"^[A-Za-z0-9_-]{43}$")
BASH_FUNCTIONS = ("generate_vless_link", "generate_clash_config")
QRENCODE_LINK_MODES = ("reality", "ws_tls", "grpc_tls", "xhttp_tls", "ws", "grpc", "xhttp")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def read_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def split_uri(uri):
    parts = urlsplit(uri)
    return parts, parse_qs(parts.query)


def clash_lines(yaml_text):
    """Return the stripped YAML lines so assertions stay formatting-agnostic."""
    return [line.strip() for line in (yaml_text or "").splitlines() if line.strip()]


def inbound(config, index=0):
    return config["inbounds"][index]


def extract_bash_function(text, name):
    match = re.search(rf"^{name}\(\) \{{\n(.*?)^\}}$", text, re.MULTILINE | re.DOTALL)
    return match.group(0) if match else None


def main(f):
    f.need(f.bash_repo is not None,
           "F18 requires --bash-repo for the fixed Bash link/Clash/QR baseline")

    work = f.evidence / "f18-work"
    if work.exists():
        shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True, exist_ok=True)
    install_sh = f.bash_repo / "install.sh"
    install_text = install_sh.read_text(encoding="utf-8")
    observed = {"generate": {}, "share": {}}

    # ---- S0: generate one real config per transport ----------------------
    specs = {
        "reality": ["--mode", "reality", "--domain", "example.com", "--port", "8443"],
        "reality-ws": ["--mode", "reality", "--transport", "ws", "--domain",
                       "example.com", "--port", "8443"],
        "tls-ws": ["--mode", "tls", "--transport", "ws", "--domain", "example.com",
                   "--port", "443"],
        "tls-grpc": ["--mode", "tls", "--transport", "grpc", "--domain", "example.com",
                     "--port", "443"],
        "tls-xhttp": ["--mode", "tls", "--transport", "xhttp", "--domain", "example.com",
                      "--port", "443"],
        "none-ws": ["--mode", "none", "--transport", "ws", "--port", "8080"],
    }
    generated = {}
    for name, extra in specs.items():
        out = work / f"{name}.json"
        r = f.run([f.go, "xray", "generate", "--out", out, "--json", *extra])
        payload = f.json_of(r, f"generate {name}") if r.rc == 0 else None
        f.check(r.rc == 0 and out.is_file(), f"generate {name} rc=0 and wrote config",
                r.text[:200])
        if payload is not None:
            generated[name] = {"path": out, "payload": payload,
                               "config": read_json(out) if out.is_file() else None}
            observed["generate"][name] = {
                "mode": payload["mode"], "transport": payload["transport"],
                "port": payload["port"],
                "inboundPorts": [i["port"] for i in read_json(out)["inbounds"]]
                if out.is_file() else [],
            }
    f.need(len(generated) == len(specs), "all six configurations were generated")
    for name, item in generated.items():
        f.check(stat.S_IMODE(item["path"].stat().st_mode) == 0o600,
                f"{name} config mode is 0600",
                oct(stat.S_IMODE(item["path"].stat().st_mode)))

    def share(name, *extra):
        return f.run([f.go, "xray", "share", "--path", generated[name]["path"],
                      "--host", "example.com", "--json", *extra])

    # ---- S1: Reality raw ------------------------------------------------
    reality_cfg = generated["reality"]["config"]
    reality_port = inbound(reality_cfg)["port"]
    reality_sid = inbound(reality_cfg)["streamSettings"]["realitySettings"]["shortIds"][0]
    reality_pbk = generated["reality"]["payload"]["publicKey"]
    reality_sha = sha256_file(generated["reality"]["path"])

    r = share("reality")
    info = f.json_of(r, "share reality") if r.rc == 0 else None
    f.check(r.rc == 0, "reality share rc=0", r.text[:200])
    if info:
        f.check(info["mode"] == "reality", "reality share mode", info["mode"])
        f.check(info["transport"] == "raw", "reality share transport", info["transport"])
        f.check(info["uuid"] == inbound(reality_cfg)["settings"]["clients"][0]["id"],
                "reality share uuid matches config client")
        f.check(info["email"] == "me@hey.run", "reality share email", info["email"])
        f.check(info["flow"] == "xtls-rprx-vision", "reality share flow", info["flow"])
        f.check(info["host"] == "example.com", "reality share host", info["host"])
        f.check(info["port"] == reality_port, "reality share port is the config port",
                str(info["port"]))
        parts, query = split_uri(info["shareUri"])
        f.check(parts.scheme == "vless", "reality URI scheme", parts.scheme)
        f.check(parts.username == info["uuid"], "reality URI user is the client uuid")
        f.check(parts.hostname == "example.com" and parts.port == reality_port,
                "reality URI authority", f"{parts.hostname}:{parts.port}")
        f.check(query.get("encryption") == ["none"], "reality URI encryption=none")
        f.check(query.get("flow") == ["xtls-rprx-vision"], "reality URI flow")
        f.check(query.get("security") == ["reality"], "reality URI security")
        f.check(query.get("sni") == ["example.com"], "reality URI sni")
        f.check(query.get("fp") == ["chrome"], "reality URI fp")
        f.check(query.get("pbk") == [reality_pbk] and PBK.match(reality_pbk) is not None,
                "reality URI pbk equals the generated public key", reality_pbk)
        f.check(query.get("sid") == [reality_sid], "reality URI sid equals config shortId",
                str(query.get("sid")))
        f.check(query.get("type") == ["raw"], "reality URI type=raw")
        f.check("spx" not in query, "reality URI has no spx without metadata")
        f.check("target" not in query,
                "reality URI has no target (Bash template does)", str(sorted(query)))
        f.check(parts.fragment == "idleleo-reality", "reality URI fragment", parts.fragment)
        f.check(info["warnings"] == [], "reality share has no warnings",
                json.dumps(info["warnings"]))
        expected_clash = [
            "proxies:",
            '- name: "idleleo-reality"',
            "type: vless",
            "server: example.com",
            f"port: {reality_port}",
            f"uuid: {info['uuid']}",
            "network: tcp",
            "udp: true",
            "tls: true",
            "servername: example.com",
            "flow: xtls-rprx-vision",
            "client-fingerprint: chrome",
            "reality-opts:",
            f"public-key: {reality_pbk}",
            f"short-id: {reality_sid}",
        ]
        lines = clash_lines(info.get("clashYaml"))
        for line in expected_clash:
            f.check(line in lines, f"reality Clash line: {line}")
        f.check("spider-x" not in "".join(lines), "reality Clash omits spider-x without metadata")
        f.check(generated["reality"]["payload"]["shareUri"] == info["shareUri"],
                "generate preview and share agree on the Reality URI")
        f.check(generated["reality"]["payload"]["clashYaml"] == info["clashYaml"],
                "generate preview and share agree on the Reality Clash proxy")
        observed["share"]["reality"] = {"uri": info["shareUri"], "port": info["port"]}
    f.check(sha256_file(generated["reality"]["path"]) == reality_sha,
            "reality share never rewrites the runtime config")

    # ---- S2: --public-port overrides only the client view ---------------
    r = share("reality", "--public-port", "443")
    info443 = f.json_of(r, "share reality public-port") if r.rc == 0 else None
    f.check(r.rc == 0, "reality share --public-port rc=0", r.text[:160])
    if info443:
        parts, _ = split_uri(info443["shareUri"])
        f.check(parts.port == 443, "public port overrides the URI port", str(parts.port))
        f.check(info443["port"] == 443, "public port appears in the JSON view",
                str(info443["port"]))
        f.check(f"port: {443}" in clash_lines(info443.get("clashYaml")),
                "public port overrides the Clash port")
    f.check(sha256_file(generated["reality"]["path"]) == reality_sha,
            "--public-port never rewrites the runtime config")

    # ---- S3: the Reality companion ws inbound ---------------------------
    rws_cfg = generated["reality-ws"]["config"]
    f.check(len(rws_cfg["inbounds"]) == 2,
            "reality --transport ws generated two inbounds", str(len(rws_cfg["inbounds"])))
    rws_port = inbound(rws_cfg, 1)["port"]
    r = share("reality-ws", "--inbound", "1")
    ws_info = f.json_of(r, "share reality-ws inbound 1") if r.rc == 0 else None
    f.check(r.rc == 0, "reality-ws companion share rc=0", r.text[:200])
    if ws_info:
        f.check(ws_info["mode"] == "none" and ws_info["transport"] == "ws",
                "companion inbound renders as plain ws",
                f"{ws_info['mode']}/{ws_info['transport']}")
        f.check(ws_info["port"] == rws_port, "companion share uses inbound 1 port",
                str(ws_info["port"]))
        parts, query = split_uri(ws_info["shareUri"])
        f.check(parts.port == rws_port, "companion URI carries inbound 1 port")
        f.check(query.get("security") == ["none"], "companion URI security=none")
        f.check(query.get("type") == ["ws"], "companion URI type=ws")
        f.check(query.get("path") == ["/ray/"], "companion URI path from wsSettings",
                str(query.get("path")))
        f.check(query.get("host") == ["example.com"], "companion URI host")
        f.check(query.get("sni") == ["example.com"],
                "companion URI sets sni from the caller host (Bash none-ws has none)")
        for absent in ("flow", "pbk", "sid", "spx"):
            f.check(absent not in query, f"companion URI has no {absent}")
        f.check(parts.fragment == "idleleo-none", "companion URI fragment",
                parts.fragment)
        lines = clash_lines(ws_info.get("clashYaml"))
        f.check("network: ws" in lines, "companion Clash network=ws")
        f.check("ws-opts:" in lines and "path: /ray/" in lines,
                "companion Clash carries the ws path")
        f.check(not any(line == "tls: true" for line in lines),
                "companion Clash is not tls")
    r = share("reality-ws", "--inbound", "9")
    f.check(r.rc == 1, "out-of-range inbound rc=1", r.text[:160])
    f.check("vless://" not in r.out, "out-of-range inbound renders no URI")

    # ---- S4: TLS ws behind a proxy --------------------------------------
    tls_ws_sha = sha256_file(generated["tls-ws"]["path"])
    r = share("tls-ws")
    f.check(r.rc == 1, "loopback security=none share is refused as ambiguous",
            r.text[:200])
    f.check("ambiguous" in r.text, "ambiguity refusal names the problem")
    f.check("--public-security" in r.text, "ambiguity refusal names the remedy")
    f.check("vless://" not in r.out, "ambiguous share renders no URI")

    r = share("tls-ws", "--public-security", "tls", "--public-port", "443")
    tls_info = f.json_of(r, "share tls-ws") if r.rc == 0 else None
    f.check(r.rc == 0, "tls-ws share with --public-security tls rc=0", r.text[:200])
    if tls_info:
        f.check(tls_info["mode"] == "tls" and tls_info["transport"] == "ws",
                "tls-ws view", f"{tls_info['mode']}/{tls_info['transport']}")
        f.check(tls_info["port"] == 443, "tls-ws public port is 443",
                str(tls_info["port"]))
        f.check(any("public-tls-terminated-by-proxy" in w for w in tls_info["warnings"]),
                "tls-ws share warns that the proxy terminates TLS",
                json.dumps(tls_info["warnings"]))
        parts, query = split_uri(tls_info["shareUri"])
        f.check(parts.port == 443, "tls-ws URI public port 443")
        f.check(query.get("security") == ["tls"], "tls-ws URI security=tls")
        f.check(query.get("sni") == ["example.com"], "tls-ws URI sni")
        f.check(query.get("type") == ["ws"], "tls-ws URI type=ws")
        f.check(query.get("path") == ["/ray/"], "tls-ws URI path")
        f.check(query.get("host") == ["example.com"], "tls-ws URI host")
        f.check("fp" not in query, "tls-ws URI has no fp (Bash always adds fp=chrome)")
        f.check("flow" not in query, "tls-ws URI has no flow")
        lines = clash_lines(tls_info.get("clashYaml"))
        for line in ("network: ws", "tls: true", "servername: example.com",
                     "ws-opts:", "path: /ray/", "Host: example.com"):
            f.check(line in lines, f"tls-ws Clash line: {line}")
        f.check("client-fingerprint: chrome" not in lines,
                "tls-ws Clash omits client-fingerprint (Bash always adds it)")
        f.check("skip-cert-verify: false" not in lines,
                "tls-ws Clash omits skip-cert-verify (Bash always adds it)")
    f.check(sha256_file(generated["tls-ws"]["path"]) == tls_ws_sha,
            "tls-ws share never rewrites the runtime config")

    # ---- S5: TLS gRPC ---------------------------------------------------
    r = share("tls-grpc", "--public-security", "tls", "--public-port", "443")
    grpc_info = f.json_of(r, "share tls-grpc") if r.rc == 0 else None
    f.check(r.rc == 0, "tls-grpc share rc=0", r.text[:200])
    if grpc_info:
        f.check(grpc_info["transport"] == "grpc", "tls-grpc transport")
        parts, query = split_uri(grpc_info["shareUri"])
        f.check(query.get("type") == ["grpc"], "tls-grpc URI type=grpc")
        f.check(query.get("serviceName") == ["idleleo-grpc"],
                "tls-grpc URI serviceName", str(query.get("serviceName")))
        f.check("path" not in query, "tls-grpc URI has no path")
        f.check(parts.port == 443, "tls-grpc URI public port 443")
        lines = clash_lines(grpc_info.get("clashYaml"))
        for line in ("network: grpc", "grpc-opts:",
                     "grpc-service-name: idleleo-grpc"):
            f.check(line in lines, f"tls-grpc Clash line: {line}")

    # ---- S6: TLS xHTTP has no Clash rendering ---------------------------
    r = share("tls-xhttp", "--public-security", "tls", "--public-port", "443")
    xhttp_info = f.json_of(r, "share tls-xhttp") if r.rc == 0 else None
    f.check(r.rc == 0, "tls-xhttp share rc=0", r.text[:200])
    if xhttp_info:
        f.check(xhttp_info["transport"] == "xhttp", "tls-xhttp transport")
        parts, query = split_uri(xhttp_info["shareUri"])
        f.check(query.get("type") == ["xhttp"], "tls-xhttp URI type=xhttp")
        f.check(query.get("path") == ["/ray/"], "tls-xhttp URI path")
        f.check(query.get("security") == ["tls"], "tls-xhttp URI security=tls")
        f.check(not xhttp_info.get("clashYaml"),
                "xhttp JSON has no Clash proxy", str(xhttp_info.get("clashYaml"))[:80])
        f.check("clash-xhttp-unsupported" in xhttp_info["warnings"],
                "xhttp share warns instead of fabricating Clash",
                json.dumps(xhttp_info["warnings"]))
    r = f.run([f.go, "xray", "share", "--path", generated["tls-xhttp"]["path"],
               "--host", "example.com", "--public-security", "tls",
               "--public-port", "443"])
    f.check(r.rc == 0, "tls-xhttp text share rc=0", r.text[:160])
    f.check("warning=clash-xhttp-unsupported" in r.out,
            "xhttp text output prints the warning")
    f.check("proxies:" not in r.out, "xhttp text output contains no Clash proxy")
    f.check("vless://" in r.out, "xhttp text output still carries the URI")

    # ---- S7: plain ws (mode none) --------------------------------------
    r = share("none-ws")
    f.check(r.rc == 1, "none ws without --public-security is refused", r.text[:200])
    f.check("ambiguous" in r.text, "none ws refusal names the ambiguity")

    r = share("none-ws", "--public-security", "none")
    none_info = f.json_of(r, "share none-ws") if r.rc == 0 else None
    f.check(r.rc == 0, "none-ws share with --public-security none rc=0", r.text[:200])
    if none_info:
        f.check(none_info["mode"] == "none" and none_info["transport"] == "ws",
                "none-ws view", f"{none_info['mode']}/{none_info['transport']}")
        f.check(none_info["port"] == 8080, "none-ws port is the config port",
                str(none_info["port"]))
        f.check(none_info["warnings"] == [], "none-ws share has no warnings")
        parts, query = split_uri(none_info["shareUri"])
        f.check(query.get("security") == ["none"], "none-ws URI security=none")
        f.check(query.get("type") == ["ws"], "none-ws URI type=ws")
        lines = clash_lines(none_info.get("clashYaml"))
        f.check("network: ws" in lines and "tls: true" not in lines,
                "none-ws Clash is plain ws")
        f.check("servername: example.com" not in lines,
                "none-ws Clash has no servername")

    r = f.run([f.go, "xray", "share", "--path", generated["none-ws"]["path"],
               "--host", "example.com", "--public-security", "none"])
    f.check(r.rc == 0, "none-ws text share rc=0", r.text[:160])
    f.check(r.out.startswith("mode=none transport=ws "),
            "none-ws text header", r.out.splitlines()[0][:120])
    f.check("\nshare: vless://" in r.out, "none-ws text output carries the share URI")
    f.check("proxies:" in r.out, "none-ws text output appends the Clash proxy")

    r = share("none-ws", "--public-security", "bogus")
    f.check(r.rc == 1, "invalid --public-security rc=1", r.text[:160])
    f.check("--public-security must be tls, none or reality" in r.text,
            "invalid --public-security is named")

    # ---- S8: terminal QR code ------------------------------------------
    plain = f.run([f.go, "xray", "share", "--path", generated["reality"]["path"],
                   "--host", "example.com"])
    f.check(plain.rc == 0 and "qr:" not in plain.out
            and "\u2588" not in plain.out and "qrencode" not in plain.out,
            "S8 share without --qr stays text-only", plain.text[:160])
    uri = next((line[len("share: "):] for line in plain.out.splitlines()
                if line.startswith("share: ")), "")
    f.check(uri.startswith("vless://"), "S8 share line carries the URI", uri[:80])

    r = f.run([f.go, "xray", "share", "--path", generated["reality"]["path"],
               "--host", "example.com", "--qr"])
    f.check(r.rc == 0, "S8 share --qr exits 0", r.text[:160])
    matrix = r.out.split("qr:\n", 1)[1] if "qr:\n" in r.out else ""
    # Clash YAML/warnings follow the matrix; the marker eats the newline that
    # belongs to qrencode's own trailing blank line, so put it back.
    for marker in ("\nwarning=", "\nproxies:"):
        if marker in matrix:
            matrix = matrix.split(marker, 1)[0] + "\n"
    f.check(matrix.strip() != "" and "\u2588" in matrix,
            "S8 --qr prints a QR matrix", matrix[:80])
    direct = subprocess.run(["qrencode", "-o", "-", "-t", "utf8"],
                            input=uri.encode("utf-8"), capture_output=True, env=f.env)
    f.check(direct.returncode == 0, "S8 real qrencode baseline runs")
    f.check(matrix.encode("utf-8") == direct.stdout,
            "S8 matrix is byte-identical to qrencode -o - -t utf8",
            f"go={hashlib.sha256(matrix.encode()).hexdigest()[:16]} "
            f"qrencode={hashlib.sha256(direct.stdout).hexdigest()[:16]}")
    f.write_json("qr-compare.json", {
        "uri": uri,
        "goQrSha256": hashlib.sha256(matrix.encode("utf-8")).hexdigest(),
        "qrencodeSha256": hashlib.sha256(direct.stdout).hexdigest(),
        "qrencodeVersion": (f.run(["qrencode", "--version"]).out.splitlines() or [""])[0],
        "bytes": len(direct.stdout),
        "lines": direct.stdout.count(b"\n"),
    })

    r = f.run([f.go, "xray", "share", "--path", generated["reality"]["path"],
               "--host", "example.com", "--json", "--qr"])
    f.check(r.rc == 2 and "--qr" in r.text,
            "S8 --json --qr is rejected (rc=2)", r.text[:160])
    f.check("\u2588" not in r.out, "S8 rejected --json --qr prints no matrix")

    no_qrcode = dict(f.env)
    no_qrcode["PATH"] = "/nonexistent-f18-qr"
    r = f.run([f.go, "xray", "share", "--path", generated["reality"]["path"],
               "--host", "example.com", "--qr"], env=no_qrcode)
    f.check(r.rc == 1 and r.out.strip() == "",
            "S8 missing qrencode fails with no partial output", r.text[:160])
    f.check("qrencode is not installed" in r.err,
            "S8 missing qrencode names the dependency", r.err[:200])

    r = f.run([f.go, "xray", "share", "--path", generated["reality"]["path"],
               "--qr-bogus"])
    f.check(r.rc == 2 and "unknown flag" in r.text,
            "S8 unknown share flag still rc=2", r.text[:160])

    # ---- S9: fixed Bash baseline ---------------------------------------
    bash_functions = {}
    for name in BASH_FUNCTIONS:
        definition = extract_bash_function(install_text, name)
        f.check(definition is not None, f"Bash function {name} found in install.sh")
        bash_functions[name] = bool(definition)
    f.need(all(bash_functions.values()),
           "the fixed Bash link/Clash baseline functions must exist")

    link_definition = extract_bash_function(install_text, "generate_vless_link")
    f.check('&target=${target}' in link_definition,
            "Bash Reality link template includes target")
    f.check('path=%2f${path}%3Fed%3D2048' in link_definition,
            "Bash ws link template hard-codes path=%2f...%3Fed%3D2048")
    f.check('mode=auto' in link_definition,
            "Bash xhttp link template includes mode=auto")
    f.check('fp=chrome' in link_definition,
            "Bash link templates always include fp=chrome")
    f.check('#${quoted_host}+ws%E5%8D%8F%E8%AE%AE' in link_definition,
            "Bash ws_tls fragment is '<host> ws协议'")
