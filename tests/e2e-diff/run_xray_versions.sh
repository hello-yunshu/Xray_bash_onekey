#!/usr/bin/env bash
# Multi-version Xray gate.
#
# Downloads the last few real stable Xray releases, generates one config with
# the pinned installer, then asks every downloaded binary to parse it
# (`xray -test`). This catches config/schema drift between the installer and an
# older runtime without inventing a synthetic config.
#
# The Bash installer itself pins its release archive through versions.json, so
# this gate is a binary-compatibility gate, not a second dual-install matrix.
# That scope is recorded in xray-versions.json.
#
# Env:
#   E2E_XRAY_COUNT      stable releases to fetch (default 3)
#   E2E_XRAY_VERSION    extra pinned version tag (default 26.10.31)
#   E2E_XRAY_DIR        download cache (default ~/.cache/xray-audit/xray)
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SUITE="$ROOT/tests/e2e-diff"
RUN_ID="${E2E_RUN_ID:-versions-$(date +%Y%m%d-%H%M)-$(git -C "$ROOT" rev-parse --short HEAD)}"
EVID="$SUITE/evidence/$RUN_ID/versions"
WORK="/tmp/e2e-$RUN_ID"
IMAGE_TAG="${E2E_IMAGE_TAG:-idleleo-e2e:24.04}"
GO_IMAGE="${E2E_GO_IMAGE:-golang:1.27.4}"
COUNT="${E2E_XRAY_COUNT:-3}"
PINNED="${E2E_XRAY_VERSION:-26.10.31}"
CACHE="${E2E_XRAY_DIR:-$HOME/.cache/xray-audit/xray}"

source "$ROOT/tests/go-parity/lib/docker_common.sh"

if [[ -d "$EVID" && -n "$(ls -A "$EVID" 2>/dev/null)" ]]; then
    echo "FATAL: $EVID already holds evidence; choose a new E2E_RUN_ID" >&2
    exit 2
fi
mkdir -p "$EVID" "$WORK" "$CACHE"
log() { printf '%s %s\n' "$(date +%H:%M:%S)" "$*" | tee -a "$EVID/run.log"; }

ARCH=$(docker_arch) || exit 2
case "$ARCH" in
    amd64) ASSET="Xray-linux-64.zip" ;;
    arm64) ASSET="Xray-linux-arm64-v8a.zip" ;;
    *) log "FATAL: unsupported arch $ARCH"; exit 2 ;;
esac

docker build -q -t "$IMAGE_TAG" -f "${E2E_IMAGE_DOCKERFILE:-$SUITE/image/Dockerfile}" "$SUITE/image" >/dev/null || {
    log "FATAL: image build failed"; exit 2
}
docker run --rm -v "$ROOT:/src:ro" -v "$WORK:/out" -w /src \
    -e CGO_ENABLED=0 -e GOFLAGS=-mod=vendor -e GOPROXY=off -e GOTOOLCHAIN=local \
    "$GO_IMAGE" go build -buildvcs=false -trimpath -o /out/idleleo ./cmd/idleleo || {
    log "FATAL: idleleo build failed"; exit 2
}

releases="$WORK/releases.json"
if ! curl -fsSL --retry 3 --connect-timeout 15 --max-time 60 \
        "https://api.github.com/repos/XTLS/Xray-core/releases?per_page=20" -o "$releases"; then
    log "FATAL: release list download failed"
    echo '{"verdict":"BLOCKED","reason":"github-api-unreachable"}' >"$EVID/xray-versions.json"
    exit 2
fi

tags=()
while IFS= read -r tag_line; do
    [[ -n "$tag_line" ]] && tags+=("$tag_line")
done < <(python3 - "$releases" "$COUNT" "$PINNED" <<'PY'
import json
import sys

data = json.load(open(sys.argv[1]))
count = int(sys.argv[2])
pinned = sys.argv[3]
tags = [x["tag_name"] for x in data
        if not x.get("prerelease") and not x.get("draft") and x.get("tag_name")]
tags = tags[:count]
if pinned and all(t.lstrip("v") != pinned.lstrip("v") for t in tags):
    tags.append(pinned if pinned.startswith("v") else "v" + pinned)
print("\n".join(tags))
PY
)

if [[ ${#tags[@]} -eq 0 ]]; then
    log "FATAL: no stable tags parsed"
    echo '{"verdict":"HARNESS-ERROR","reason":"no-stable-tags"}' >"$EVID/xray-versions.json"
    exit 2
fi

# One config shared by every binary: generated by the pinned installer build.
SEED="$WORK/seed"
mkdir -p "$SEED"
cp "$WORK/idleleo" "$SEED/idleleo"
NEWEST="${tags[0]}"
if [[ -x "$ROOT/tests/go-parity/.cache/a2/xray" ]]; then
    cp "$ROOT/tests/go-parity/.cache/a2/xray" "$SEED/xray"
else
    cp "$(ensure_xray_bin "$ARCH")" "$SEED/xray"
fi
chmod 0755 "$SEED/idleleo" "$SEED/xray"

# shellcheck disable=SC2046
docker run -d --name "e2e-$RUN_ID-versions" --hostname "e2e-$RUN_ID-versions" \
    --privileged --cgroupns=host --tmpfs /run --tmpfs /run/lock \
    $(cgroup_mount_args) -v "$SEED:/seed:ro" -v "$EVID:/out" \
    "$IMAGE_TAG" /usr/lib/systemd/systemd >/dev/null || {
    log "FATAL: container start failed"; exit 2
}
trap 'docker rm -f "e2e-$RUN_ID-versions" >/dev/null 2>&1 || true' EXIT
for _ in $(seq 1 60); do
    state=$(docker exec "e2e-$RUN_ID-versions" systemctl is-system-running 2>/dev/null || true)
    [[ "$state" == "running" || "$state" == "degraded" ]] && break
    sleep 1
done
docker exec "e2e-$RUN_ID-versions" install -m 0755 /seed/idleleo /usr/local/bin/idleleo
docker exec "e2e-$RUN_ID-versions" install -m 0755 /seed/xray /usr/local/bin/xray
docker exec -e IDLELEO_ALLOW_SYSTEM_WRITES=I_ACCEPT_CONTAINER_ONLY \
    "e2e-$RUN_ID-versions" idleleo xray install --binary /usr/local/bin/xray \
    --mode reality --domain example.com --target www.cloudflare.com \
    --port 443 --container --json >"$EVID/install.json" 2>"$EVID/install.err"
if [[ $? -ne 0 ]]; then
    log "FATAL: config generation failed"
    echo '{"verdict":"HARNESS-ERROR","reason":"config-generation-failed"}' >"$EVID/xray-versions.json"
    exit 2
fi
docker cp "e2e-$RUN_ID-versions:/etc/idleleo/conf/xray/config.json" "$EVID/xray.config.json" >/dev/null

results="$EVID/results.tsv"
: >"$results"

# deploy_and_probe boots a throwaway systemd container with the release binary,
# performs a real Go install and a real client business request. `xray -test` is
# kept as the first gate, but it is never reported as a deployment.
deploy_and_probe() { # <tag> <binary-dir> <out-dir>
    local tag=$1 bindir=$2 out=$3
    local safe did dnet dc
    safe=$(printf '%s' "$tag" | tr -c 'A-Za-z0-9' '_')
    did="ver-$safe"
    dnet="e2e-$RUN_ID-$did-net"
    dc="e2e-$RUN_ID-$did"
    mkdir -p "$out" "$WORK/secret/$tag"
    docker network create "$dnet" >/dev/null 2>&1 || true
    # shellcheck disable=SC2046
    if ! docker run -d --name "$dc" --hostname "$dc" --network "$dnet" \
            --privileged --cgroupns=host --tmpfs /run --tmpfs /run/lock \
            $(cgroup_mount_args) \
            -v "$ROOT:/src:ro" -v "$bindir:/xray-bin:ro" -v "$SEED:/seed:ro" -v "$out:/out" \
            "$IMAGE_TAG" /usr/lib/systemd/systemd >/dev/null 2>&1; then
        printf 'BLOCKER\tcontainer-start\n' >"$out/deploy.txt"
        return 2
    fi
    local st=""
    for _ in $(seq 1 60); do
        st=$(docker exec "$dc" systemctl is-system-running 2>/dev/null || true)
        [[ "$st" == running || "$st" == degraded ]] && break
        sleep 1
    done
    docker exec "$dc" install -m 0755 /seed/idleleo /usr/local/bin/idleleo
    docker exec "$dc" install -m 0755 /xray-bin/xray /usr/local/bin/xray
    docker exec -e IDLELEO_ALLOW_SYSTEM_WRITES=I_ACCEPT_CONTAINER_ONLY "$dc" \
        idleleo xray install --binary /usr/local/bin/xray --mode reality \
        --domain example.com --target www.cloudflare.com --port 443 \
        --container --json >"$out/install.json" 2>"$out/install.err"
    local irc=$?
    echo "$irc" >"$out/install.rc"
    if [[ "$irc" -ne 0 ]]; then
        printf 'BLOCKER\tinstall-rc=%s\n' "$irc" >"$out/deploy.txt"
        docker rm -f "$dc" >/dev/null 2>&1; docker network rm "$dnet" >/dev/null 2>&1
        return 3
    fi
    local client_xray="${E2E_CLIENT_XRAY:-}"
    [[ -n "$client_xray" && -x "$client_xray" ]] || client_xray="$SEED/xray"
    bash "$SUITE/collect/l4.sh" "$dc" "$dc-client" "$IMAGE_TAG" "$dnet" \
        reality example.com "$client_xray" "$WORK/secret/$tag" "$out/connectivity" auto \
        >"$out/l4.log" 2>&1
    local lrc=$?
    echo "$lrc" >"$out/l4.rc"
    if [[ "$lrc" -eq 0 ]]; then
        printf 'PASS\tclient-business-request\n' >"$out/deploy.txt"
    else
        printf 'BLOCKER\tclient-l4-rc=%s\n' "$lrc" >"$out/deploy.txt"
    fi
    docker rm -f "$dc" >/dev/null 2>&1 || true
    docker network rm "$dnet" >/dev/null 2>&1 || true
    return "$lrc"
}

for tag in "${tags[@]}"; do
    ver="${tag#v}"
    dir="$CACHE/$tag"
    mkdir -p "$dir"
    zip="$dir/$ASSET"
    if [[ ! -f "$zip" ]]; then
        if ! curl -fsSL --retry 3 --connect-timeout 15 --max-time 300 \
                -o "$zip.tmp" \
                "https://github.com/XTLS/Xray-core/releases/download/$tag/$ASSET" ||
           ! mv "$zip.tmp" "$zip"; then
            rm -f "$zip.tmp"
            printf '%s\t%s\t%s\t%s\n' "$tag" "BLOCKED" "download-failed" "0" >>"$results"
            log "tag=$tag BLOCKED download-failed"
            continue
        fi
    fi
    sha=$(shasum -a 256 "$zip" | awk '{print $1}')
    unzip -oq "$zip" -d "$dir/bin" xray || {
        printf '%s\t%s\t%s\t%s\n' "$tag" "BLOCKED" "unzip-failed" "$sha" >>"$results"
        log "tag=$tag BLOCKED unzip-failed"
        continue
    }
    rc=0
    # The generated config logs to /var/log/xray/*.log, a directory the systemd
    # unit creates at runtime. This throwaway probe container has no unit, so
    # provision the same directory instead of letting a missing dir mask the
    # real parse result.
    # Mount the binary outside /bin: replacing /bin would hide /bin/sh and make
    # the probe fail with 127 instead of a config verdict.
    docker run --rm -v "$dir/bin:/xray-bin:ro" -v "$EVID:/out:ro" \
        "$IMAGE_TAG" sh -c 'mkdir -p /var/log/xray && exec /xray-bin/xray -test -config /out/xray.config.json' \
        >"$EVID/$tag.test.log" 2>&1 || rc=$?
    reported=$(docker run --rm -v "$dir/bin:/xray-bin:ro" "$IMAGE_TAG" /xray-bin/xray version 2>/dev/null | head -1)
    if [[ "$rc" -eq 0 ]]; then
        dverdict="NOT-RUN"; ddetail="deploy-not-attempted"
        deploy_and_probe "$tag" "$dir/bin" "$EVID/$tag-deploy" || true
        if [[ -f "$EVID/$tag-deploy/deploy.txt" ]]; then
            dverdict=$(cut -f1 "$EVID/$tag-deploy/deploy.txt")
            ddetail=$(cut -f2 "$EVID/$tag-deploy/deploy.txt")
        else
            dverdict="BLOCKER"; ddetail="missing-deploy-evidence"
        fi
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$tag" "PASS" "$reported" "$sha" "$tag/$ASSET" \
            "$dverdict" "$ddetail" >>"$results"
        log "tag=$tag config=PASS deploy=$dverdict ($ddetail)"
    else
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$tag" "BLOCKER" "config-test-rc=$rc" "$sha" "$tag/$ASSET" \
            "NOT-RUN" "config-test-failed" >>"$results"
        log "tag=$tag BLOCKER config-test-rc=$rc"
    fi
done

python3 - "$results" "$EVID/xray-versions.json" "$NEWEST" "$ASSET" <<'PY'
import json
import sys

rows, out, newest, asset = sys.argv[1:]
items = []
for line in open(rows, encoding="utf-8"):
    parts = line.rstrip("\n").split("\t")
    if len(parts) < 4:
        continue
    tag, verdict, detail, sha = parts[:4]
    deploy_verdict = parts[5] if len(parts) > 5 else "NOT-RUN"
    deploy_detail = parts[6] if len(parts) > 6 else ""
    items.append({"tag": tag, "verdict": verdict, "detail": detail,
                  "sha256": sha, "asset": asset,
                  "deployVerdict": deploy_verdict,
                  "deployDetail": deploy_detail})
verdict = "PASS"
if not items:
    verdict = "HARNESS-ERROR"
elif any(x["verdict"] == "BLOCKER" or x["deployVerdict"] == "BLOCKER" for x in items):
    verdict = "BLOCKER"
elif all(x["verdict"] == "BLOCKED" for x in items):
    verdict = "BLOCKED"
elif any(x["deployVerdict"] != "PASS" for x in items):
    verdict = "BLOCKER"
report = {
    "verdict": verdict,
    "configSource": "idleleo xray install --mode reality (pinned build)",
    "newestTag": newest,
    "scope": ("config compatibility plus a real data-plane deployment and "
              "client business request for every release that parses the config"),
    "versions": items,
}
with open(out, "w", encoding="utf-8") as fh:
    json.dump(report, fh, indent=2, sort_keys=True)
    fh.write("\n")
print(verdict)
PY

log "done"
